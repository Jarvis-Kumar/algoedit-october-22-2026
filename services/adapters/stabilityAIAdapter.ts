
import { BaseProviderAdapter, AIRequest, AIResponse } from './baseAdapter';
import * as fal from "@fal-ai/serverless-client";
import { config } from '../config';

export class StabilityAIAdapter extends BaseProviderAdapter {
  constructor(config: any) {
    super(config);
  }

  async execute(request: AIRequest): Promise<AIResponse> {
    console.log(`[StabilityAIAdapter via Fal.ai] Executing ${request.taskType} via ${this.config.name}`);
    
    const falKey = config.fal.apiKey || process.env.FAL_KEY;
    if (!falKey) {
      throw new Error("FAL_KEY is not configured.");
    }
    
    fal.config({ credentials: falKey });

    const result = await fal.subscribe("fal-ai/stable-diffusion", {
      input: {
        prompt: request.prompt,
        image_size: "square_hd"
      }
    }) as any;

    const imageUrl = result.images?.[0]?.url || result.image?.url;
    if (!imageUrl) {
      throw new Error("No image generated by Fal AI Stable Diffusion adapter.");
    }

    return {
      text: imageUrl,
      usage: { prompt_tokens: 0, completion_tokens: 0 }
    };
  }
}

