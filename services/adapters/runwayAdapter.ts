
import { BaseProviderAdapter, AIRequest, AIResponse } from './baseAdapter';
import * as fal from "@fal-ai/serverless-client";
import { config } from '../config';

export class RunwayAdapter extends BaseProviderAdapter {
  constructor(config: any) {
    super(config);
  }

  async execute(request: AIRequest): Promise<AIResponse> {
    console.log(`[RunwayAdapter via Fal.ai] Executing ${request.taskType} via ${this.config.name}`);
    
    const falKey = config.fal.apiKey || process.env.FAL_KEY;
    if (!falKey) {
      throw new Error("FAL_KEY is not configured.");
    }
    
    fal.config({ credentials: falKey });

    const inputData: any = {
      prompt: request.prompt || "cinematic panning zoom action"
    };

    if (request.base64ImageData) {
      inputData.image_url = request.base64ImageData;
    }

    const result = await fal.subscribe("fal-ai/luma-dream-machine", {
      input: inputData
    }) as any;

    const videoUrl = result.video?.url || result.output?.video?.url || result.url;
    if (!videoUrl) {
      throw new Error("No video generated by Fal AI Luma Dream Machine adapter.");
    }

    return {
      text: videoUrl,
      usage: { prompt_tokens: 0, completion_tokens: 0 }
    };
  }
}

